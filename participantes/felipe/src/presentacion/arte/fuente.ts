const SIN_TILDE: Record<string, string> = {
  "Á": "A",
  "É": "E",
  "Í": "I",
  "Ó": "O",
  "Ú": "U",
  "Ü": "U",
  "¿": "?",
  "¡": "!",
};

export function normalizar(texto: string): string {
  let salida = "";
  for (const caracter of texto.toUpperCase()) {
    if (caracter === "\n") {
      salida += caracter;
      continue;
    }
    const limpio = SIN_TILDE[caracter] ?? caracter;
    salida += GLIFOS[limpio] ? limpio : " ";
  }
  return salida;
}
